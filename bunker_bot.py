@bot.callback_query_handler(func=lambda call: True)
def handle_callback(call):
    uid = call.message.chat.id
    state = user_state.get(uid)
    if not state or 'card'not in state:
        bot.answer_callback_query(call.id, "Сначала нажмите /card!")
        return

    card = state['card']
    msg_id = state['msg_id']
    data = call.data

    # 1️⃣ Навигация
    if data == 'change_char_menu':
        bot.edit_message_reply_markup(chat_id=uid, message_id=msg_id, reply_markup=get_char_select_markup())
        bot.answer_callback_query(call.id)
        return
    if data.startswith('change_char:'):
        _, field = data.split(':', 1)
        bot.edit_message_reply_markup(chat_id=uid, message_id=msg_id, reply_markup=get_submenu_markup(field))
        bot.answer_callback_query(call.id)
        return
    if data == 'back_to_main':
        bot.edit_message_reply_markup(chat_id=uid, message_id=msg_id, reply_markup=get_main_markup())
        bot.answer_callback_query(call.id)
        return

    # 2️⃣ Реролл конкретного поля (включая индексы)
    if data.startswith('reroll_field:'):
        _, field, idx = data.split(':', 2)
        state['card'] = reroll_specific(card, field, idx)
        safe_edit_text(uid, msg_id, format_card(state['card']), get_main_markup())
        
        ru_name = FIELD_NAMES_RU.get(field, field)
        if idx == 'random':
            bot.answer_callback_query(call.id, f"🎲 Случайный {ru_name} обновлен")
        else:
            bot.answer_callback_query(call.id, f"✅ {ru_name} {int(idx)+1} обновлен")
        return

    # 3️⃣ Скачивание
    if data == 'download_txt':
        txt_content = format_card_txt(card)
        buf = io.BytesIO(txt_content.encode('utf-8'))
        buf.name = 'bunker_card.txt'
        bot.send_document(uid, buf, caption='📄 Ваша карточка в формате .txt')
        bot.answer_callback_query(call.id, "Файл отправлен 📩")
        buf.close()
        return

    # 4️⃣ Полный / Случайный реролл
    if data == 'reroll_all':
        state['card'] = generate_card()
    elif data == 'reroll_random':
        field = random.choice(list(FIELD_POOLS.keys()))
        state['card'] = reroll_specific(card, field, 'random')

    safe_edit_text(uid, msg_id, format_card(state['card']), get_main_markup())
    bot.answer_callback_query(call.id)

