@bot.message_handler(commands=['card'])
def handle_card(message):
    uid = message.chat.id
    user_state[uid] = {'card': generate_card()}
    msg = bot.send_message(uid, format_card(user_state[uid]['card']), reply_markup=get_main_markup(), parse_mode='HTML')
